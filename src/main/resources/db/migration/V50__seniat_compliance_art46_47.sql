-- Cumplimiento SENIAT (Providencia máquinas fiscales, Art. 46 y 47).
-- Solo agrega estructuras nuevas y columnas nullable; no elimina ni altera datos existentes.

-- 1) Art. 46 c) y f): desincorporación (el estatus 'desincorporada' de impresoras se mantiene).
CREATE TABLE IF NOT EXISTS public.impresora_desincorporaciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_impresora  BIGINT      NOT NULL REFERENCES public.impresoras (id),
    fecha         DATE        NOT NULL DEFAULT CURRENT_DATE,
    motivo        VARCHAR(20) NOT NULL
        CONSTRAINT chk_desincorporacion_motivo CHECK (motivo IN ('DESUSO', 'SUSTITUCION', 'PERDIDA', 'OTRO')),
    es_propia     BOOLEAN     NOT NULL DEFAULT FALSE,
    id_usuario    BIGINT      REFERENCES public.users (id),
    observaciones TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_desincorporaciones_id_impresora ON public.impresora_desincorporaciones (id_impresora);
CREATE INDEX IF NOT EXISTS idx_desincorporaciones_fecha ON public.impresora_desincorporaciones (fecha);

-- Relleno histórico: impresoras ya desincorporadas (hoy no hay ninguna; queda por seguridad).
INSERT INTO public.impresora_desincorporaciones (id_impresora, fecha, motivo, observaciones)
SELECT i.id, i.created_at::date, 'OTRO', 'Registro histórico generado por migración V50'
FROM public.impresoras i
WHERE i.estatus = 'desincorporada'
  AND NOT EXISTS (SELECT 1 FROM public.impresora_desincorporaciones d WHERE d.id_impresora = i.id);

-- 2) Art. 46 h): desarrollador de software ajeno, con RIF vía empresas.rif.
ALTER TABLE public.software
    ADD COLUMN IF NOT EXISTS id_empresa_desarrolladora BIGINT NULL REFERENCES public.empresas (id),
    ADD COLUMN IF NOT EXISTS es_externo BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX IF NOT EXISTS idx_software_id_empresa_desarrolladora ON public.software (id_empresa_desarrolladora);

-- 3) Art. 46 e): historial de inclusión y exclusión de distribuidores y centros de servicio.
ALTER TABLE public.distribuidoras
    ADD COLUMN IF NOT EXISTS fecha_inclusion DATE NULL,
    ADD COLUMN IF NOT EXISTS fecha_exclusion DATE NULL;
ALTER TABLE public.centros_servicio
    ADD COLUMN IF NOT EXISTS fecha_inclusion DATE NULL,
    ADD COLUMN IF NOT EXISTS fecha_exclusion DATE NULL;

UPDATE public.distribuidoras d
SET fecha_inclusion = COALESCE(
    (SELECT MIN(c.fecha_inicio) FROM public.contratos_distribuidoras c WHERE c.id_distribuidora = d.id),
    d.created_at::date)
WHERE d.fecha_inclusion IS NULL;

UPDATE public.centros_servicio s
SET fecha_inclusion = COALESCE(
    (SELECT MIN(c.fecha_inicio) FROM public.contratos_centros_servicio c WHERE c.id_centro_servicio = s.id),
    s.created_at::date)
WHERE s.fecha_inclusion IS NULL;

-- 4) Art. 46 g) e i): libro de anormalidades.
CREATE TABLE IF NOT EXISTS public.anormalidades (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_impresora    BIGINT      NOT NULL REFERENCES public.impresoras (id),
    tipo            VARCHAR(30) NOT NULL
        CONSTRAINT chk_anormalidad_tipo CHECK (tipo IN
            ('PRECINTO_ALTERADO', 'PRECINTO_REMOVIDO', 'MODIFICACION_FUNCIONAL', 'PERDIDA', 'OTRA')),
    fecha_deteccion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    autorizado      BOOLEAN     NOT NULL DEFAULT FALSE,
    id_usuario      BIGINT      REFERENCES public.users (id),
    descripcion     TEXT,
    origen          VARCHAR(20) NOT NULL DEFAULT 'MANUAL'
        CONSTRAINT chk_anormalidad_origen CHECK (origen IN ('INSPECCION', 'SERVICIO', 'MANUAL')),
    id_origen       BIGINT      NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_anormalidades_id_impresora ON public.anormalidades (id_impresora);
CREATE INDEX IF NOT EXISTS idx_anormalidades_fecha_deteccion ON public.anormalidades (fecha_deteccion);

-- 5) Declaración mensual: el payload es JSON genérico (formato de envío al SENIAT pendiente).
CREATE TABLE IF NOT EXISTS public.declaraciones_seniat (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio         SMALLINT    NOT NULL,
    mes          SMALLINT    NOT NULL CHECK (mes BETWEEN 1 AND 12),
    fecha_limite DATE        NULL,
    fecha_envio  TIMESTAMP WITH TIME ZONE NULL,
    estado       VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CONSTRAINT chk_declaracion_estado CHECK (estado IN ('PENDIENTE', 'ENVIADA', 'ACEPTADA', 'RECHAZADA')),
    acuse        TEXT        NULL,
    payload      JSONB       NULL,
    id_usuario   BIGINT      REFERENCES public.users (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_declaracion_periodo UNIQUE (anio, mes)
);

